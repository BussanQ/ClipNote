//go:build darwin

package main

import (
	"errors"
	"os"
	"runtime"
	"unsafe"

	"github.com/ebitengine/purego"
	"github.com/ebitengine/purego/objc"
)

type macDesktop struct {
	preflight, request func() bool
	createKey          func(uintptr, uint16, bool) uintptr
	setFlags           func(uintptr, uint64)
	post               func(int32, uintptr)
	release            func(uintptr)
}

func newDesktop() (desktop, error) {
	cg, err := purego.Dlopen("/System/Library/Frameworks/CoreGraphics.framework/CoreGraphics", purego.RTLD_LAZY|purego.RTLD_LOCAL)
	if err != nil {
		return nil, err
	}
	cf, err := purego.Dlopen("/System/Library/Frameworks/CoreFoundation.framework/CoreFoundation", purego.RTLD_LAZY|purego.RTLD_LOCAL)
	if err != nil {
		return nil, err
	}
	d := &macDesktop{}
	purego.RegisterLibFunc(&d.preflight, cg, "CGPreflightPostEventAccess")
	purego.RegisterLibFunc(&d.request, cg, "CGRequestPostEventAccess")
	purego.RegisterLibFunc(&d.createKey, cg, "CGEventCreateKeyboardEvent")
	purego.RegisterLibFunc(&d.setFlags, cg, "CGEventSetFlags")
	purego.RegisterLibFunc(&d.post, cg, "CGEventPostToPid")
	purego.RegisterLibFunc(&d.release, cf, "CFRelease")
	return d, nil
}
func cls(name string) objc.ID { return objc.ID(objc.GetClass(name)) }
func send[T any](obj objc.ID, name string, args ...any) T {
	if obj == 0 {
		var zero T
		return zero
	}
	return objc.Send[T](obj, objc.RegisterName(name), args...)
}
func ns(text string) objc.ID {
	obj := send[objc.ID](cls("NSString"), "alloc")
	obj = send[objc.ID](obj, "initWithBytes:length:encoding:", uintptr(unsafe.Pointer(unsafe.StringData(text))), uintptr(len(text)), uintptr(4))
	runtime.KeepAlive(text)
	return send[objc.ID](obj, "autorelease")
}
func board() objc.ID     { return send[objc.ID](cls("NSPasteboard"), "generalPasteboard") }
func workspace() objc.ID { return send[objc.ID](cls("NSWorkspace"), "sharedWorkspace") }
func frontApp() objc.ID  { return send[objc.ID](workspace(), "frontmostApplication") }
func goString(str objc.ID) string {
	n := send[uintptr](str, "lengthOfBytesUsingEncoding:", uintptr(4))
	if n == 0 || n > 1024 {
		return ""
	}
	ptr := send[*byte](str, "UTF8String")
	if ptr == nil {
		return ""
	}
	return string(unsafe.Slice(ptr, n))
}
func (d *macDesktop) front() pasteTarget {
	return pasteTarget{pid: send[int32](frontApp(), "processIdentifier")}
}
func (d *macDesktop) preparePaste(target pasteTarget, _ uintptr) bool {
	return d.front() == target
}
func (d *macDesktop) frontInfo() (int32, string, string) {
	app := frontApp()
	return send[int32](app, "processIdentifier"),
		goString(send[objc.ID](app, "localizedName")),
		goString(send[objc.ID](app, "bundleIdentifier"))
}
func (d *macDesktop) appIconPNG(bundleID string) []byte {
	if bundleID == "" || len(bundleID) > 1024 {
		return nil
	}
	ws := workspace()
	url := send[objc.ID](ws, "URLForApplicationWithBundleIdentifier:", ns(bundleID))
	path := send[objc.ID](url, "path")
	if path == 0 {
		return nil
	}
	icon := send[objc.ID](ws, "iconForFile:", path)
	tiff := send[objc.ID](icon, "TIFFRepresentation")
	if tiff == 0 {
		return nil
	}
	rep := send[objc.ID](cls("NSBitmapImageRep"), "imageRepWithData:", tiff)
	if rep == 0 {
		return nil
	}
	const pngType = uintptr(4) // NSBitmapImageFileTypePNG
	properties := send[objc.ID](cls("NSDictionary"), "dictionary")
	data := send[objc.ID](rep, "representationUsingType:properties:", pngType, properties)
	n := send[uintptr](data, "length")
	if n == 0 || n > 8<<20 {
		return nil
	}
	ptr := send[*byte](data, "bytes")
	if ptr == nil {
		return nil
	}
	return append([]byte(nil), unsafe.Slice(ptr, n)...)
}
func (d *macDesktop) canPaste() bool { return d.preflight() }
func (d *macDesktop) askPaste() bool { return d.request() }
func (d *macDesktop) count() int64   { return send[int64](board(), "changeCount") }
func (d *macDesktop) read() (string, bool) {
	pb := board()
	types := send[objc.ID](pb, "types")
	// Avoid file paths, auto-generated transfers, and secrets whose source marks them.
	for _, typ := range []string{"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "public.file-url", "NSFilenamesPboardType"} {
		if send[bool](types, "containsObject:", ns(typ)) {
			return "", false
		}
	}
	str := send[objc.ID](pb, "stringForType:", ns("public.utf8-plain-text"))
	if str == 0 {
		return "", false
	}
	n := send[uintptr](str, "lengthOfBytesUsingEncoding:", uintptr(4))
	if n == 0 || n > 1<<20 {
		return "", false
	}
	ptr := send[*byte](str, "UTF8String")
	if ptr == nil {
		return "", false
	}
	return string(unsafe.Slice(ptr, n)), true
}
func (d *macDesktop) paste(target pasteTarget, text string) (err error) {
	pid := target.pid
	if pid <= 0 || pid == int32(os.Getpid()) || d.front() != target {
		return errors.New("原应用不在前台，已取消粘贴")
	}
	if !d.canPaste() {
		return errors.New("需要在系统设置中允许「辅助功能」后再试")
	}
	// Placement is performed by the original application. Never click a new
	// location, read the field, or send the event to whichever app is active later.
	const keyV = 9
	const command = 1 << 20
	down, up := d.createKey(0, keyV, true), d.createKey(0, keyV, false)
	if down != 0 {
		defer d.release(down)
	}
	if up != 0 {
		defer d.release(up)
	}
	if down == 0 || up == 0 {
		return errors.New("无法生成系统粘贴按键")
	}
	item := send[objc.ID](send[objc.ID](cls("NSPasteboardItem"), "alloc"), "init")
	if item == 0 {
		return errors.New("无法创建纯文本剪贴板条目")
	}
	defer send[struct{}](item, "release")
	if !send[bool](item, "setString:forType:", ns(text), ns("public.utf8-plain-text")) {
		return errors.New("无法创建纯文本剪贴板条目")
	}
	// Mark our own transfers before publishing to avoid duplicates and races.
	send[bool](item, "setString:forType:", ns(""), ns("org.nspasteboard.AutoGeneratedType"))
	items := send[objc.ID](cls("NSArray"), "arrayWithObject:", item)
	pb := board()
	send[int64](pb, "clearContents")
	if !send[bool](pb, "writeObjects:", items) {
		return errors.New("无法写入系统剪贴板")
	}

	if d.front() != target {
		return errors.New("原应用已切换：文本已复制，请手动粘贴")
	}
	d.setFlags(down, command)
	d.setFlags(up, command)
	d.post(pid, down)
	d.post(pid, up)
	return nil
}
